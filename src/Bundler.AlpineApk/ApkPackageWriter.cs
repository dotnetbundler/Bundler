using System.Text;
using DotNet.Bundler;
using DotNet.Bundler.Core;
using DotNet.Bundler.Core.Update;

namespace DotNet.Bundler.AlpineApk;

/// <summary>
/// Emits an .apk entirely in managed code. An apk v2 file is three concatenated
/// gzip streams — signature tar, control tar (.PKGINFO + scripts), data tar
/// (payload). The signature and control tars omit the final pair of zero
/// blocks; the data tar keeps them. Gzip output is deterministic (mtime 0),
/// so identical inputs produce identical bytes.
/// </summary>
internal static class ApkPackageWriter
{
    internal sealed class Result
    {
        internal string Path = "";
    }

    private sealed class PayloadEntry
    {
        internal string ArchivePath = "";      // tar-relative, no leading '.'
        internal TarEntryKind Kind;
        internal string? SourcePath;            // host path when Kind=File
        internal byte[]? Content;               // generated bytes for Kind=File without SourcePath
        internal int Mode;
        internal string LinkTarget = "";        // for Kind=Symlink
        internal long Size;                     // file size for the PKGINFO 'size' field
    }

    internal static Result Build(
        BundleConfiguration bundle,
        BundlePlanItem item,
        AlpineApkBundleConfiguration settings,
        IBundleLogger logger)
    {
        // 与门面 Validate 同一条校验链——直调 writer 也得到一致异常契约。
        ApkValidation.Settings(settings, bundle);
        var resolved = ApkValidation.Target(settings, bundle, item.Target);
        var packageName = resolved.PackageName;
        var pkgver = resolved.PkgVer;
        var architecture = resolved.Architecture;
        var installRoot = resolved.InstallRoot;
        var binLink = resolved.BinLink;
        var origin = resolved.Origin;
        var description = resolved.Description;
        var url = resolved.Url;
        var license = resolved.License;
        var buildDate = resolved.BuildDate;

        var payload = CollectPayload(bundle, item, installRoot, binLink, packageName, settings, logger);

        // Data segment first: .PKGINFO carries the sha256 of its gzip stream.
        // data tar.gz 是大件——直写输出目录旁的临时文件不驻内存（/tmp 小卷不堵
        // 构建——目标目录反正得装下成品）；control/签名段 KB 级留内存。
        Directory.CreateDirectory(item.OutputDirectory);
        var dataGzipPath = Path.Combine(item.OutputDirectory,
            ".bundler-apk-" + Guid.NewGuid().ToString("N") + ".tar.gz");
        try
        {
            GzipTarToFile(payload, dataGzipPath, omitEndOfArchive: false);
            var dataHash = Hashes.Sha256HexFile(dataGzipPath);
        var installedSize = payload
            .Where(entry => entry.Kind == TarEntryKind.File)
            .Sum(entry => entry.Size);

        var pkginfo = PackageInfo(
            packageName, pkgver, description, url, architecture, origin, license, buildDate,
            installedSize, dataHash, settings);
        var controlEntries = new List<TarEntry>
        {
            new()
            {
                Name = ".PKGINFO",
                Kind = TarEntryKind.File,
                Mode = 420, // 0644
                Content = new UTF8Encoding(false).GetBytes(pkginfo),
                PaxRecords = TimestampRecords
            }
        };
        EmitScripts(controlEntries, settings);
        var controlGzip = Gzip.Compress(TarData(controlEntries, omitEndOfArchive: true));

        // Optional signature segment: a tar holding .SIGN.RSA.<key name>.rsa.pub
        // whose content is the raw PKCS1v15 RSA-SHA1 signature over the control
        // gzip stream. It precedes the control segment. The member name must
        // match the trusted public key file in /etc/apk/keys/<name>.rsa.pub —
        // strip the private key's own ".rsa"/".rsa.pub" suffix first or apk
        // looks up a key that never exists.
        byte[]? signatureGzip = null;
        if (settings.Signing.KeyFile is { Length: > 0 } keyFile)
        {
            var signature = ApkSigner.Sign(controlGzip, keyFile, settings.Signing.Passphrase);
            var keyName = Path.GetFileName(keyFile);
            if (keyName.EndsWith(".rsa.pub", StringComparison.Ordinal))
            {
                keyName = keyName.Substring(0, keyName.Length - ".rsa.pub".Length);
            }
            else if (keyName.EndsWith(".rsa", StringComparison.Ordinal))
            {
                keyName = keyName.Substring(0, keyName.Length - ".rsa".Length);
            }
            var memberName = ".SIGN.RSA." + keyName + ".rsa.pub";
            signatureGzip = Gzip.Compress(TarData(
            [
                new TarEntry
                {
                    Name = memberName,
                    Kind = TarEntryKind.File,
                    Mode = 420, // 0644
                    Content = signature,
                    PaxRecords = TimestampRecords
                }
            ], omitEndOfArchive: true));
        }
        else if (settings.Signing.Passphrase is { Length: > 0 })
        {
            throw new ArgumentException(
                "Signing.Passphrase requires Signing.KeyFile to point at a PEM RSA private key.");
        }

        Directory.CreateDirectory(item.OutputDirectory);
        var fileName = packageName + "-" + pkgver + "." + architecture + ".apk";
        var outputPath = Path.Combine(item.OutputDirectory, fileName);
        if (File.Exists(outputPath))
        {
            File.Delete(outputPath);
        }

        logger.Log(BundleLogLevel.Information, $"Writing apk → {fileName}");
        try
        {
            using (var stream = new FileStream(outputPath, FileMode.Create, FileAccess.Write, FileShare.None))
            {
                if (signatureGzip is not null)
                {
                    stream.Write(signatureGzip, 0, signatureGzip.Length);
                }
                stream.Write(controlGzip, 0, controlGzip.Length);
                using (var dataStream = File.OpenRead(dataGzipPath))
                {
                    dataStream.CopyTo(stream);
                }
            }
        }
        catch
        {
            // No half-written package is left behind on failure; 同删陈旧
            // .sha256 旁车，避免失败构建留下与实际产物不匹配的哈希。
            if (File.Exists(outputPath))
            {
                File.Delete(outputPath);
            }
            if (File.Exists(outputPath + ".sha256"))
            {
                File.Delete(outputPath + ".sha256");
            }
            throw;
        }
        return new Result { Path = outputPath };
        }
        finally
        {
            TryDelete(dataGzipPath);
        }
    }

    private static void TryDelete(string path)
    {
        try
        {
            if (File.Exists(path))
            {
                File.Delete(path);
            }
        }
        catch
        {
            // 临时件清扫失败不遮主流程。
        }
    }

    private static string PackageInfo(
        string packageName,
        string pkgver,
        string description,
        string url,
        string architecture,
        string origin,
        string license,
        string buildDate,
        long installedSize,
        string dataHash,
        AlpineApkBundleConfiguration settings)
    {
        var builder = new StringBuilder();
        void Field(string key, string value)
        {
            if (value.Contains('\n') || value.Contains('\r'))
            {
                throw new ArgumentException(
                    $"The .PKGINFO field '{key}' cannot contain line breaks.");
            }
            builder.Append(key).Append(" = ").Append(value).Append('\n');
        }
        Field("pkgname", packageName);
        Field("pkgver", pkgver);
        Field("pkgdesc", description);
        if (url.Length > 0)
        {
            Field("url", url);
        }
        Field("arch", architecture);
        Field("origin", origin);
        if (license.Length > 0)
        {
            Field("license", license);
        }
        foreach (var depend in settings.Depends ?? [])
        {
            Field("depend", depend);
        }
        foreach (var provide in settings.Provides ?? [])
        {
            Field("provides", provide);
        }
        if (settings.Triggers is { Count: > 0 } triggers)
        {
            Field("triggers", string.Join(" ", triggers));
        }
        Field("builddate", buildDate);
        Field("size", installedSize.ToString());
        Field("datahash", dataHash);
        if (settings.ExtraPkgInfo is not null)
        {
            foreach (var pair in settings.ExtraPkgInfo)
            {
                Field(pair.Key, pair.Value);
            }
        }
        return builder.ToString();
    }

    /// <summary>The six apk control-script knobs and their dotted member names.</summary>
    internal static (string? Path, string Name)[] ScriptKnobs(AlpineApkBundleConfiguration settings) =>
    [
        (settings.PreInstallFile, ".pre-install"),
        (settings.PostInstallFile, ".post-install"),
        (settings.PreUninstallFile, ".pre-deinstall"),
        (settings.PostUninstallFile, ".post-deinstall"),
        (settings.PreUpgradeFile, ".pre-upgrade"),
        (settings.PostUpgradeFile, ".post-upgrade")
    ];

    // apk install scripts live in the control segment as dotted names
    // (.pre-install, ...). Like rpm scriptlets they must use LF line endings —
    // and no UTF-8 BOM, which busybox would read as garbage before the shebang.
    internal static byte[] ReadScript(string path, string name)
    {
        var full = Path.GetFullPath(path);
        if (!File.Exists(full))
        {
            throw new FileNotFoundException(
                $"The .apk script '{name}' does not exist: {full}", full);
        }
        var bytes = File.ReadAllBytes(full);
        var hasBom = bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF;
        if (bytes.Length == 0 || hasBom ||
            Encoding.UTF8.GetString(bytes).Contains('\r'))
        {
            throw new ArgumentException(
                $"The .apk script '{name}' must be non-empty UTF-8 with LF line " +
                $"endings and no BOM: {full}");
        }
        return bytes;
    }

    private static void EmitScripts(List<TarEntry> controlEntries, AlpineApkBundleConfiguration settings)
    {
        foreach (var (path, name) in ScriptKnobs(settings))
        {
            if (path is null)
            {
                continue;
            }
            controlEntries.Add(new TarEntry
            {
                Name = name,
                Kind = TarEntryKind.File,
                Mode = 493, // 0755
                Content = ReadScript(path, name),
                PaxRecords = TimestampRecords
            });
        }
    }

    private static List<PayloadEntry> CollectPayload(
        BundleConfiguration bundle,
        BundlePlanItem item,
        string installRoot,
        string binLink,
        string packageName,
        AlpineApkBundleConfiguration settings,
        IBundleLogger logger)
    {
        var entries = new List<PayloadEntry>();
        var book = new PayloadPathBook(
            onNewDirectory: directory => entries.Add(new PayloadEntry
            {
                ArchivePath = directory,
                Kind = TarEntryKind.Directory,
                Mode = 493 /* 0755 */
            }));

        void ClaimDirectory(string? path) => book.ClaimDirectory(path);

        void AddFile(string archivePath, string sourcePath, int mode)
        {
            book.ClaimFile(archivePath);
            entries.Add(new PayloadEntry
            {
                ArchivePath = archivePath,
                Kind = TarEntryKind.File,
                SourcePath = sourcePath,
                Mode = mode,
                Size = new FileInfo(sourcePath).Length
            });
        }

        void AddLink(string archivePath, string linkTarget)
        {
            book.ClaimFile(archivePath);
            entries.Add(new PayloadEntry
            {
                ArchivePath = archivePath,
                Kind = TarEntryKind.Symlink,
                Mode = 511 /* 0777 */,
                LinkTarget = linkTarget
            });
        }

        void AddGeneratedFile(string archivePath, byte[] content, int mode)
        {
            book.ClaimFile(archivePath);
            entries.Add(new PayloadEntry
            {
                ArchivePath = archivePath,
                Kind = TarEntryKind.File,
                Content = content,
                Mode = mode,
                Size = content.Length
            });
        }

        var mainExecutable = item.MainExecutable.Replace('\\', '/');
        // 空目录也要落条目：仅按文件路径反推会丢无文件目录。
        foreach (var sourceItem in PayloadSource.CollectInput(item.InputDirectory, installRoot, mainExecutable, logger))
        {
            if (sourceItem.Kind == PayloadSourceKind.Directory)
            {
                ClaimDirectory(sourceItem.ArchivePath);
            }
            else if (sourceItem.Kind == PayloadSourceKind.Symlink)
            {
                AddLink(sourceItem.ArchivePath, sourceItem.LinkTarget!);
            }
            else
            {
                AddFile(sourceItem.ArchivePath, sourceItem.SourcePath!, sourceItem.Mode);
            }
        }

        foreach (var sourceItem in PayloadSource.CollectResources(bundle.Resources, installRoot, logger, includeDirectories: true))
        {
            if (sourceItem.Kind == PayloadSourceKind.Directory)
            {
                ClaimDirectory(sourceItem.ArchivePath);
            }
            else if (sourceItem.Kind == PayloadSourceKind.Symlink)
            {
                AddLink(sourceItem.ArchivePath, sourceItem.LinkTarget!);
            }
            else
            {
                AddFile(sourceItem.ArchivePath, sourceItem.SourcePath!, sourceItem.Mode);
            }
        }

        // 更新面：身份旁车（含 pkg 包名——换包按它定位已装单元）+ 引导件（apk 只产
        // linux-musl 目标，per-target musl 静态件直中）随包装进安装根，与用户载荷同权：
        // 撞名走 claimed 冲突显式拒绝，不静默覆盖。
        if (bundle.Update is { } update)
        {
            var target = item.Target.Target;
            AddGeneratedFile(
                installRoot + "/" + UpdateInstallIdentity.FileName,
                UpdateIdentitySidecar.Serialize(update, PackageFormat.AlpineApk, target, packageName),
                420 /* 0644 */);
            AddFile(
                installRoot + "/" + UpdateBootstrapper.FileNameFor(target),
                UpdateBootstrapper.ResolveOrThrow(update, target), 493 /* 0755 */);
        }

        foreach (var file in settings.Files ?? [])
        {
            var destination = FreedesktopFiles.NormalizeAbsoluteDestination(
                file.Destination, "alpineapk");
            AddFile(destination.TrimStart('/'),
                Path.GetFullPath(file.Source), 420 /* 0644 */);
        }

        if (binLink.Length > 0)
        {
            AddLink("usr/bin/" + binLink, "../lib/" + packageName + "/" + mainExecutable);
        }

        return entries;
    }

    // data tar 直写 gzip→文件：TarWriter 的 OpenContent 已惰性流源文件，
    // 这一层再把 tar/gzip 字节驻内存才是唯一的整量缓冲点。
    private static void GzipTarToFile(
        IEnumerable<PayloadEntry> entries, string path, bool omitEndOfArchive)
    {
        using var file = new FileStream(path, FileMode.Create, FileAccess.Write, FileShare.None);
        using (var gzip = Gzip.WrapWrite(file))
        {
            TarWriter.Write(gzip, entries
                .OrderBy(entry => entry.ArchivePath, StringComparer.Ordinal)
                .Select(entry => new TarEntry
                {
                    Name = entry.ArchivePath,
                    Kind = entry.Kind,
                    Mode = entry.Mode,
                    Content = [],
                    OpenContent = entry.Kind != TarEntryKind.File
                        ? null
                        : entry.Content is { } content
                            ? () => (Stream)new MemoryStream(content, writable: false)
                            : () => new FileStream(entry.SourcePath!, FileMode.Open, FileAccess.Read, FileShare.Read),
                    LinkTarget = entry.LinkTarget,
                    PaxRecords = PayloadPaxRecords(entry)
                }), omitEndOfArchive);
        }
    }

    private static byte[] TarData(IEnumerable<TarEntry> entries, bool omitEndOfArchive)
    {
        using var buffer = new MemoryStream();
        TarWriter.Write(buffer, entries, omitEndOfArchive);
        return buffer.ToArray();
    }

    // Every apk entry carries atime/ctime = 0 like abuild output; regular
    // files add the APK-TOOLS.checksum.SHA1 pax record (hex sha1 of content,
    // hex sha1 of the link target for symlinks) that apk requires to extract.
    private static readonly KeyValuePair<string, string>[] TimestampRecords =
    [
        new("ctime", "0"),
        new("atime", "0")
    ];

    private static KeyValuePair<string, string>[] PayloadPaxRecords(PayloadEntry entry)
    {
        if (entry.Kind is not (TarEntryKind.File or TarEntryKind.Symlink))
        {
            return TimestampRecords;
        }
        string hash;
        if (entry.Kind == TarEntryKind.Symlink)
        {
            hash = Hashes.Sha1Hex(new UTF8Encoding(false).GetBytes(entry.LinkTarget));
        }
        else if (entry.Content is { } content)
        {
            hash = Hashes.Sha1Hex(content);
        }
        else
        {
            using var stream = new FileStream(
                entry.SourcePath!, FileMode.Open, FileAccess.Read, FileShare.Read);
            hash = Hashes.Sha1Hex(stream);
        }
        return
        [
            new("ctime", "0"),
            new("atime", "0"),
            new("APK-TOOLS.checksum.SHA1", hash)
        ];
    }

}
